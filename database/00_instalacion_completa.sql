delete from asignaciones
where id not in (
  select min(id)
  from asignaciones
  group by materia_id, grupo_id
);

delete from grupos
where id not in (
  select min(id)
  from grupos
  group by nombre, turno
);

delete from materias
where id not in (
  select min(id)
  from materias
  group by clave
);

delete from alumno_accesos
where id not in (
  select min(id)
  from alumno_accesos
  group by alumno_id, modulo
);

