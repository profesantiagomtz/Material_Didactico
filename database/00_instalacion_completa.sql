select m.id, g.id, true
from materias m
join grupos g on
  (m.clave = 'COBD' and g.nombre = '410')
  or (m.clave = 'COBD' and g.nombre = '411')
  or (m.clave = 'POO' and g.nombre = '411')
  or (m.clave = 'MRDE' and g.nombre = '611')
on conflict (materia_id, grupo_id) do update set activa = true;

